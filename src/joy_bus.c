void EnableJoyBusInterrupt(void)
{
    u16 enabled = REG_IME;
    REG_IME = 0;
    REG_IE |= INTR_FLAG_SERIAL;
    REG_IME = enabled;
}

void DisableJoyBusInterrupt(void)
{
    u16 enabled = REG_IME;
    REG_IME = 0;
    REG_IE &= (u16)~INTR_FLAG_SERIAL;
    REG_IF = INTR_FLAG_SERIAL;
    REG_IME = enabled;
}

