void InitializeJoyBusContext(JoyBusContext * context)
{
    gJoyBusContext = context;
    context->state = 0;
    ResetJoyBusCommandQueue();
    gJoyBusContext->unk_04 = 0;
    gJoyBusContext->unk_08 = 0;
}

