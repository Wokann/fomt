inline void TownMapMarkers::PushBack(TownMapMarker const & value)
{
    if (last != capacity_end) {
        std::construct(last, value);
        ++last;
    } else {
        u32 count = 1;
        u32 size = last - first;
        u32 capacity = size + std::max(size, count);
        TownMapMarker * storage = nullptr;
        if (capacity != 0) {
            storage = static_cast<TownMapMarker *>(malloc(capacity * sizeof(TownMapMarker)));
            if (storage == nullptr)
                storage = static_cast<TownMapMarker *>(RetryMemoryAllocation(capacity * sizeof(TownMapMarker)));
        }
        TownMapMarker * end = storage;
        for (TownMapMarker const * source = first; source != last; ++source, ++end)
            std::construct(end, *source);
        end = std::uninitialized_fill_n(end, count, value);
        std::destroy(first, last);
        if (first != nullptr)
            free(first);
        first = storage;
        last = end;
        capacity_end = storage + capacity;
    }
}

void FadeInTownMap(TownMapUiCore * core)
{
    GetHardwareDisplayState(reinterpret_cast<void * const *>(core))->SetBlendControl(BLDCNT_TGT1_ALL);
    HardwareBlendObject blend(GetHardwareDisplayState(reinterpret_cast<void * const *>(core)));
    blend.blend.Begin(0x889, 1, 1);
    GetHardwareCommandList(reinterpret_cast<void * const *>(core))->Append(&blend);
    while (blend.IsLinked()) {
        DrawTownMap(core);
        UpdateHardwareFrame(core);
    }
}

void FadeOutTownMap(TownMapUiCore * core)
{
    GetHardwareDisplayState(reinterpret_cast<void * const *>(core))->SetBlendControl(BLDCNT_TGT1_ALL);
    HardwareBlendObject blend(GetHardwareDisplayState(reinterpret_cast<void * const *>(core)));
    blend.blend.End(0x889, 1, 1);
    GetHardwareCommandList(reinterpret_cast<void * const *>(core))->Append(&blend);
    while (blend.IsLinked()) {
        DrawTownMap(core);
        UpdateHardwareFrame(core);
    }
}

