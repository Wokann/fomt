void UiTextWindow::Open()
{
    u32 previous = phase;
    if (previous == HIDDEN) {
        u32 copy_mode = mode;
        if (copy_mode != 1)
            pending_uploads.Append(&upload);
        pending_uploads.Append(&border);
        frame = previous;
    }
    switch (phase) {
    case HIDDEN:
    case OPENING:
    case CLOSING:
        phase = OPENING;
        break;
    case VISIBLE:
        break;
    default:
        break;
    }
}

void UiTextWindow::OpenImmediate()
{
    Open();
    phase = VISIBLE;
    frame = 9;
}

void UiTextWindow::Close()
{
    if (phase != HIDDEN)
        phase = CLOSING;
}

void UiTextWindow::CloseImmediate()
{
    if (phase != HIDDEN)
        phase = HIDDEN;
}

