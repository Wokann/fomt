#pragma implementation "ui_text_commands.hh"
#include "ui_text_commands.hh"

// The queue command retains its native implementation while its pointer-range
// erase expression is recovered. All transfers still use the real DMA API.
asm_unified(
    ".text\n"
    ".include \"asm/macro.inc\"\n"
    "thumb_func_start Run__20UiDmaTransferCommand\n"
    "Run__20UiDmaTransferCommand:\n"
    "push {r4, r5, lr}\n"
    "ldr r5, [r0, #12]\n"
    "movs r0, #0\n"
    "ldr r1, [r5]\n"
    "cmp r1, #0\n"
    "bne .Lui_dma_not_empty\n"
    "movs r0, #1\n"
    ".Lui_dma_not_empty:\n"
    "cmp r0, #0\n"
    "bne .Lui_dma_done\n"
    "adds r4, r5, #4\n"
    "lsls r1, r1, #4\n"
    "adds r1, r4, r1\n"
    "adds r0, r4, #0\n"
    "bl ExecuteBiosTransfers\n"
    "ldr r0, [r5]\n"
    "lsls r0, r0, #4\n"
    "adds r0, #4\n"
    "adds r0, r5, r0\n"
    "adds r2, r0, #0\n"
    "adds r1, r4, #0\n"
    "ldr r3, [r5]\n"
    "cmp r1, r2\n"
    "beq .Lui_dma_clear\n"
    ".Lui_dma_next:\n"
    "adds r1, #16\n"
    "cmp r1, r2\n"
    "bne .Lui_dma_next\n"
    ".Lui_dma_clear:\n"
    "subs r0, r0, r4\n"
    "asrs r0, r0, #4\n"
    "subs r0, r3, r0\n"
    "str r0, [r5]\n"
    ".Lui_dma_done:\n"
    "movs r0, #0\n"
    "pop {r4, r5}\n"
    "pop {r1}\n"
    "bx r1\n"
    ".align 2, 0\n"
);
