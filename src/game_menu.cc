MenuGridPosition GameSceneMenuCorePrefix::GetCursorPosition(i32 index) const
{
    MenuGridPosition position;
    switch (index) {
    case 0:
        if (left_panel.value != nullptr)
            position = GetMenuGridLeftHeaderPosition(left_panel.value);
        break;
    case 9:
        if (right_panel.value != nullptr)
            position = GetMenuGridRightHeaderPosition(right_panel.value);
        break;
    default:
        if (index <= 8) {
            if (left_panel.value != nullptr)
                position = GetMenuGridLeftCellPosition(left_panel.value, index - 1);
        } else {
            if (right_panel.value != nullptr)
                position = GetMenuGridRightCellPosition(right_panel.value, index - 10);
        }
        break;
    }
    return position;
}

i32 GameSceneMenuCorePrefix::GetItemIndex(i32 selection, i32 page) const
{
    i32 offset;
    if (selection <= 8)
        offset = (page << 3) - 1;
    else
        offset = (page << 3) - 10;
    return selection + offset;
}

