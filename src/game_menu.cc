i32 GameSceneMenuCursorData::MoveLeft()
{
    RefreshBounds();
    i32 next = gMenuGridNavigation[selection].left;
    if (next <= 8)
    {
        if (next == 0)
        {
            u8 header = core->left_panel.value->state.show_header;
            if (header == 0)
                next = selection;
        }
        else
        {
            while (next > left_limit)
            {
                if (left_limit <= 4)
                    next = left_limit;
                else
                    next = gMenuGridNavigation[next].left;
            }
        }
        if (next == 4 && previous == left_limit && previous > 4)
            next = previous;
    }
    else
    {
        if (next == 9)
        {
            u8 header = core->right_panel.value->state.show_header;
            if (header == 0)
                next = 0;
        }
        else
        {
            while (next > right_limit)
            {
                if (right_limit <= 13)
                    next = right_limit;
                else
                    next = gMenuGridNavigation[next].left;
            }
        }
        if (next == 13 && previous == right_limit && previous > 13)
            next = previous;
    }
    if (next != selection)
    {
        previous = selection;
        selection = next;
    }
    return next;
}

