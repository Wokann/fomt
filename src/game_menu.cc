i32 GameSceneMenuCursorData::MoveUp()
{
    RefreshBounds();
    i32 next = gMenuGridNavigation[selection].up;
    if (selection == 0)
    {
        if (previous != 9)
        {
            u32 column = previous - 5;
            next = previous + 4;
            if (column <= 3)
                next = previous;
        }
    }
    else if (selection == 9 && previous != 0)
    {
        u32 column = previous - 14;
        next = previous + 4;
        if (column <= 3)
            next = previous;
    }
    i32 old;
    if (next <= 8)
    {
        old = selection;
        if (next == 0 && core->left_panel.value->state.show_header == 0)
            next = old + 4;
        while (next > left_limit)
            next = gMenuGridNavigation[next].up;
    }
    else
    {
        old = selection;
        if (next == 9 && core->right_panel.value->state.show_header == 0)
            next = old + 4;
        while (next > right_limit)
            next = gMenuGridNavigation[next].up;
    }
    if (next != old)
    {
        previous = old;
        selection = next;
    }
    return next;
}

