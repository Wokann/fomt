void EraseTownMapMarkerNodes(TownMapMarkerCounts * counts, TownMapMarkerNode * node)
{
    while (node != nullptr) {
        EraseTownMapMarkerNodes(counts, static_cast<TownMapMarkerNode *>(node->right));
        TownMapMarkerNode * left = static_cast<TownMapMarkerNode *>(node->left);
        if (node != nullptr)
            free(node);
        node = left;
    }
}

