#include "libc_random.h"

u32 gRandomSeed = 1;

asm_unified(
    "    .include \"asm/macro.inc\"\n"
    "    .section .text, \"ax\", %progbits\n"
    "    .thumb\n"
    "\n"
    "    @ Seed storage is the existing writable IWRAM object, not a second state.\n"
    "    @ srand stores all 32 bits; rand advances modulo 2^32 and returns 31 bits.\n"
    "    thumb_func_start srand\n"
    "srand:\n"
    "    ldr r1, .LRandomConstants\n"
    "    str r0, [r1, #0]\n"
    "    bx lr\n"
    "    .align 2, 0\n"
    "\n"
    "    thumb_func_start rand\n"
    "rand:\n"
    "    adr r0, .LRandomConstants\n"
    "    ldm r0!, {r1, r2, r3}\n"
    "    ldr r0, [r1]\n"
    "    muls r0, r2, r0\n"
    "    adds r0, r0, r3\n"
    "    str r0, [r1]\n"
    "    lsls r0, r0, #1\n"
    "    lsrs r0, r0, #1\n"
    "    bx lr\n"
    "    .align 2, 0\n"
    ".LRandomConstants: .word gRandomSeed\n"
    "    .word 0x41C64E6D\n"
    "    .word 12345\n"
    "\n"
);
