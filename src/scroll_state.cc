static inline void SetScrollBufferTransfers(ScrollBufferUploadCommand * command,
    void const * first, void * target, u32 bytes,
    void const * second, void * other_target, u32 other_bytes)
{
    command->first_source = first;
    command->first_destination = target;
    command->first_bytes = bytes;
    command->second_source = second;
    command->second_destination = other_target;
    command->second_bytes = other_bytes;
}

