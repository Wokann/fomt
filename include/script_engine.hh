struct ScriptStack
{
    void Clear()
    {
        top = 0;
        memset(data, 0, sizeof(data));
    }

    int & Top() { return data[top - 1]; }

    void Pop()
    {
        if (top != 0)
            top--;
    }

    void Push(int const & val)
    {
        if (top < SCRIPT_STACK_MAX)
        {
            data[top++] = val;
        }
    }

    i32 data[SCRIPT_STACK_MAX];
    u32 top;
};

